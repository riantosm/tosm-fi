/**
 * Dates are generated relative to "today" (instead of hardcoded) so the demo
 * dataset always spans "3 months ago" through "this month" regardless of when
 * the app is run. Hour is kept within 9-20 local time to avoid the UTC
 * conversion in `toISOString()` shifting the calendar day.
 */
function relativeDate(monthsAgo: number, day: number, hour = 12): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = now.getMonth() - monthsAgo;
  const daysInTargetMonth = new Date(year, month + 1, 0).getDate();
  const clampedDay = Math.min(day, daysInTargetMonth);
  return new Date(year, month, clampedDay, hour, 0, 0, 0).toISOString();
}

